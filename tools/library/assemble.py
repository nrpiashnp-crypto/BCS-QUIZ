import os,re,glob
T={1:'বাংলাদেশের ভূগোল: প্রাকৃতিক বৈশিষ্ট্য ও এর পরিবর্তন',2:'বাংলাদেশের জনগোষ্ঠী ও ক্ষুদ্র নৃগোষ্ঠী',3:'বাংলাদেশের ইতিহাস ও সংস্কৃতি',
4:'বাংলাদেশের অর্থনীতি, সমাজ, সাহিত্য ও সংস্কৃতি',5:'বাংলাদেশের পরিবেশ ও প্রকৃতি',6:'বাংলাদেশের প্রাকৃতিক সম্পদ: টেকসই ব্যবহার ও ব্যবস্থাপনা',
7:'বাংলাদেশের সংবিধান',8:'সরকারের অঙ্গসমূহ: আইনসভা, নির্বাহী বিভাগ ও বিচার বিভাগ',9:'বাংলাদেশের পররাষ্ট্র সম্পর্ক',10:'বাংলাদেশের রাজনৈতিক দলসমূহ',
11:'বাংলাদেশের নির্বাচন ব্যবস্থা',12:'সমসাময়িক তথ্য, যোগাযোগ প্রযুক্তি ও ই-গভর্নেন্স',13:'অনানুষ্ঠানিক প্রতিষ্ঠান, সুশীল সমাজ, স্বার্থগোষ্ঠী ও এনজিও',
14:'বিশ্বায়ন ও বাংলাদেশ',15:'বাংলাদেশের লৈঙ্গিক ইস্যু ও উন্নয়ন',16:'মুক্তিযুদ্ধ ও এর পটভূমি'}
bn=str.maketrans('0123456789','০১২৩৪৫৬৭৮৯')
W='/tmp/claude-0/ocrwork'; O=W+'/out/BD_Affairs_Written_OCR'
idx=['# বাংলাদেশ বিষয়াবলি (বিসিএস লিখিত) — OCR টেক্সট\n','উৎস: Google Drive ফোল্ডার "live written bangladesh affairs" (Live Written স্টাডি ম্যাটেরিয়াল, ১৬ অধ্যায়)। Tesseract 5 (Bengali + English) দিয়ে OCR করা। প্রতিটি পৃষ্ঠার শুরুতে `<!-- পৃষ্ঠা N -->` চিহ্ন আছে। টেবিল ও ডায়াগ্রামের লেখা পুরোপুরি নির্ভুল নাও হতে পারে; গুরুত্বপূর্ণ সংখ্যা মূল PDF-এর সাথে মিলিয়ে নিন।\n','| ফাইল | অধ্যায় | পৃষ্ঠা |','|---|---|---|']
for n in range(1,17):
    c=f'ch{n:02d}'; pages=sorted(glob.glob(f'{W}/{c}/p-*.md'))
    body=[f'# অধ্যায় {str(n).translate(bn)}: {T[n]}\n']
    for i,p in enumerate(pages,1):
        s=open(p,encoding='utf-8').read()
        s=re.sub(r'^\s*(?:=»|=>|—>|->|=|»|>|©|\+|e|°|¢)\s+(?=[ঀ-৿])','• ',s,flags=re.M)
        s=re.sub(r'\s*\.{3,}[^\n]*?(\d+)\s*$',lambda m:' … '+m.group(1).translate(bn),s,flags=re.M)
        t89=str.maketrans('089','০৪৯')
        s=re.sub(r'(?:(?<=[\u0980-\u09FF] )|^)([089][089.,%]*)(?=[ ,]+[\u0980-\u09FF])',lambda m:m.group(1).translate(t89),s,flags=re.M)
        s=re.sub(r'(?<=[\u0980-\u09FF।)] )1 (?=[\u0980-\u09FF])','',s)
        s=re.sub(r'^©,','৫,',s,flags=re.M)
        s=re.sub(r'\n{3,}','\n\n',s).strip()
        body.append(f'<!-- পৃষ্ঠা {i} -->\n\n{s}\n')
    fn=f'{n:02d}_Chapter_{n}.md'
    open(f'{O}/{fn}','w',encoding='utf-8').write('\n'.join(body))
    idx.append(f'| {fn} | {T[n]} | {len(pages)} |')
open(f'{O}/00_README_Index.md','w',encoding='utf-8').write('\n'.join(idx)+'\n')
