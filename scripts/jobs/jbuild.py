def post_line(c: dict, n: int = 3) -> str:
    names = [p["name"] for p in c.get("posts", [])]
    s = ", ".join(names[:n])
    return s + (f" ও আরও {bn(len(names) - n)}টি পদ" if len(names) > n else "")


def age_line(c: dict) -> str:
    if not c.get("age_max"):
        return "বিজ্ঞপ্তি দেখুন"
    s = (f"{bn(c['age_min'])}–" if c.get("age_min") else "সর্বোচ্চ ") + f"{bn(c['age_max'])} বছর"
    if c.get("age_ref_date"):
        s += f" ({dlabel(c['age_ref_date'])} তারিখে)"
    return s


def jdata(c: dict) -> str:
    d = {"end": (c.get("apply_end") or "")[:10], "ref": c.get("age_ref_date"), "min": c.get("age_min"),
         "max": c.get("age_max"), "relax": c.get("age_relax") or [], "edu": c.get("edu_level"), "type": c.get("type"),
         "g": sorted({p["grade"] for p in c.get("posts", []) if isinstance(p.get("grade"), int)})}
    return esc(json.dumps(d, ensure_ascii=False, separators=(",", ":")))


