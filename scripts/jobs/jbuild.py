def public(c: dict) -> dict:
    return {k: c.get(k) for k in PUBLIC if c.get(k) not in (None, "", [])}


def build_all(records: list[dict], today: str | None = None) -> list[str]:
    """records = প্রকাশযোগ্য সব বিজ্ঞপ্তি (খোলা আর শেষ হওয়া)। ফল: বদলানো ফাইলের তালিকা।"""
    today = today or now_dhaka().date().isoformat()
    changed = []

    def put(rel: str, text: str):
        if write(CIRC_DIR / rel, text):
            changed.append(f"circular/{rel}")

    def putj(rel: str, data):
        p = DATA_DIR / rel
        old = p.read_text(encoding="utf-8") if p.exists() else None
        write_json(p, data)
        if p.read_text(encoding="utf-8") != old:
            changed.append(f"circular/data/{rel}")

    recs = [public(r) for r in records]
    open_list = sorted((r for r in recs if (r.get("apply_end") or "")[:10] >= today), key=lambda r: r["apply_end"])
    putj("open.json", {"updated": today, "circulars": [
        {k: r.get(k) for k in ("id", "org", "type", "posts", "total_posts", "apply_end", "age_ref_date", "age_min",
                                "age_max", "edu_level", "edu_line") if r.get(k) is not None} for r in open_list]})
    for r in recs:
        putj(f"{r['id']}.json", r)
        put(f"{r['id']}/index.html", detail_page(r, today))
    months: dict[str, list] = {}
    for r in recs:
        if (r.get("apply_end") or "")[:10] < today:
            months.setdefault((r.get("apply_end") or r.get("published") or today)[:7], []).append(r["id"])
    for ym, ids in months.items():
        putj(f"archive/{ym}.json", {"month": ym, "ids": sorted(ids)})
    put("index.html", index_page(open_list))
    return changed


