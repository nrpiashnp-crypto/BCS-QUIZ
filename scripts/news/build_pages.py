bn = lambda n: str(n).translate(_BN)


def dlabel(date: str, weekday: bool = False) -> str:
    d = dt.date.fromisoformat(date)
    s = f"{bn(d.day)} {MONTHS[d.month - 1]} {bn(d.year)}"
    return f"{s}, {WEEKDAYS[d.weekday()]}" if weekday else s


def mlabel(ym: str) -> str:
    y, m = ym.split("-")
    return f"{MONTHS[int(m) - 1]} {bn(int(y))}"


def day_path(date: str) -> str:
    y, m, d = date.split("-")
    return f"/news/{y}/{m}/{d}/"


def month_path(ym: str) -> str:
    y, m = ym.split("-")
    return f"/news/{y}/{m}/"


