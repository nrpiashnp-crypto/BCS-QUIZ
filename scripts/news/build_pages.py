def ribbon() -> str:
    """[আজকের ঘটনা | নিয়োগ বিজ্ঞপ্তি]; /circular/ তৈরি না হওয়া পর্যন্ত দ্বিতীয় ঘর লিংকহীন (ভাঙা লিংক নয়)।"""
    second = ('<a href="/circular/">নিয়োগ বিজ্ঞপ্তি</a>' if (ROOT / "circular/index.html").exists()
              else '<span class="off" aria-disabled="true">নিয়োগ বিজ্ঞপ্তি<small>শীঘ্রই</small></span>')
    return f'<div class="rib"><a href="/news/" aria-current="page">আজকের ঘটনা</a>{second}</div>\n'


def crumb(*parts) -> str:
    out = ['<a href="/">হোম</a>']
    for href, text in parts:
        out.append(f'<a href="{href}">{esc(text)}</a>' if href else f"<span>{esc(text)}</span>")
    return '<nav class="crumb" aria-label="অবস্থান">' + " › ".join(out) + "</nav>\n"


def article(it: dict) -> str:
    facts = "".join(f"<dt>{esc(f['label'])}</dt><dd>{esc(f['value'])}</dd>" for f in it.get("facts", []))
    src = "".join(f'<a href="{esc(s["url"])}" rel="noopener nofollow" target="_blank">{esc(s["name"])}</a>' for s in it.get("sources", []))
    return (f'<article id="{esc(it["id"])}">\n<h3>{esc(it["title"])}</h3>\n<p>{esc(it["detail"])}</p>\n'
            + (f'<p class="w"><b>পরীক্ষায় কেন:</b> {esc(it["why_exam"])}</p>\n' if it.get("why_exam") else "")
            + (f"<details><summary>তথ্য-ছক</summary><dl class=\"f\">{facts}</dl></details>\n" if facts else "")
            + (f'<p class="src">মূল খবর:{src}</p>\n' if src else "")
            + "</article>\n")


def by_section(day: dict) -> list[tuple[str, list[dict]]]:
    items = [*day.get("top", []), *day.get("more", [])]
    out = []
    for sec, name in (day.get("sections") or SECTIONS).items():
        got = sorted((x for x in items if x.get("section") == sec), key=lambda x: -x["score"])
        if got:
            out.append((name, got))
    return out


def neighbours(dates: list[str], date: str):
    """dates নতুন থেকে পুরোনো; ফল: (পুরোনো পাশের দিন, নতুন পাশের দিন)।"""
    i = dates.index(date)
    return (dates[i + 1] if i + 1 < len(dates) else None), (dates[i - 1] if i else None)


def day_page(day: dict, dates: list[str], months: set[str]) -> str:
    date = day["date"]
    secs = by_section(day)
    total = sum(len(g) for _, g in secs)
    first = (secs[0][1][0]["title"] if secs else "")
    desc = f"{dlabel(date)}-এর গুরুত্বপূর্ণ ঘটনা, পরীক্ষার জন্য: {first}" + (f" আর আরও {bn(total - 1)}টা।" if total > 1 else "")
    h = [head(f"আজকের ঘটনা: {dlabel(date)} · লিয়ানা বুকস", desc, day_path(date)), ribbon(),
         crumb(("/news/", "খবর"), (None, dlabel(date))),
         f"<h1>{esc(dlabel(date, True))}</h1>\n<p class=\"sub\">{bn(total)}টা ঘটনা, তিন ভাগে</p>\n"]
    if secs:
        h.append('<p class="jump">' + "".join(f'<a href="#s{i}">{esc(n)} ({bn(len(g))})</a>' for i, (n, g) in enumerate(secs)) + "</p>\n")
    else:
        h.append("<p>এই দিনে প্রকাশযোগ্য খবর নেই।</p>\n")
    for i, (name, group) in enumerate(secs):
        h.append(f'<h2 class="sh" id="s{i}">{esc(name)}</h2>\n' + "".join(article(x) for x in group))
    older, newer = neighbours(dates, date)
    h.append('<div class="pn">' + (f'<a href="{day_path(older)}">← {esc(dlabel(older))}</a>' if older else "<span></span>")
             + (f'<a class="r" href="{day_path(newer)}">{esc(dlabel(newer))} →</a>' if newer else "") + "</div>\n")
    ym = date[:7]
    if ym in months:
        h.append(f'<p class="mo"><a href="{month_path(ym)}">{esc(mlabel(ym))}-এর সব বড় ঘটনা →</a></p>\n')
    h.append(foot())
    return "".join(h)


def landing(latest: dict, idx: list[dict], months: list[str]) -> str:
    date = latest["date"]
    top = latest.get("top", [])
    desc = "বিসিএস ও চাকরির পরীক্ষার জন্য প্রতিদিনের গুরুত্বপূর্ণ ঘটনা: বাংলাদেশ, আন্তর্জাতিক আর সাধারণ জ্ঞান।"
    h = [head("আজকের ঘটনা: প্রতিদিনের গুরুত্বপূর্ণ খবর, পরীক্ষার জন্য · লিয়ানা বুকস", desc, "/news/"), ribbon(),
         "<h1>আজকের ঘটনা</h1>\n" f'<p class="sub">{esc(dlabel(date, True))}</p>\n', '<ol class="top">\n']
    for it in top:
        h.append(f'<li><small>{esc(it["section_bn"])}</small><a href="{day_path(date)}#{esc(it["id"])}">{esc(it["title"])}</a>'
                 f'<p>{esc(it["short"])}</p></li>\n')
    h.append("</ol>\n")
    more = len(latest.get("more", []))
    h.append(f'<a class="go" href="{day_path(date)}">আজকের পূর্ণ পাতা পড়ুন'
             + (f" (আরও {bn(more)}টা ঘটনা)" if more else "") + "</a>\n")
    older = [d for d in idx if d["date"] != date][:LANDING_N]
    if older:
        h.append('<h2 class="sh">আগের দিন</h2>\n<ul class="days">\n')
        h.extend(f'<li><a href="{day_path(d["date"])}">{esc(dlabel(d["date"], True))}</a><span>{bn(d["n"])}টা ঘটনা</span></li>\n' for d in older)
        h.append("</ul>\n")
    if months:
        h.append('<h2 class="sh">মাসের বড় ঘটনা</h2>\n<ul class="days">\n')
        h.extend(f'<li><a href="{month_path(m)}">{esc(mlabel(m))}</a></li>\n' for m in months)
        h.append("</ul>\n")
    h.append(foot())
    return "".join(h)


def month_page(month: dict, months: list[str]) -> str:
    ym = month["month"]
    items = sorted(month.get("items", []), key=lambda x: (x["date"], -x["score"]), reverse=True)
    h = [head(f"{mlabel(ym)}-এর বড় ঘটনা · লিয়ানা বুকস",
              f"{mlabel(ym)}-এর সবচেয়ে গুরুত্বপূর্ণ ঘটনা, পরীক্ষার প্রস্তুতির জন্য।", month_path(ym)), ribbon(),
         crumb(("/news/", "খবর"), (None, mlabel(ym))),
         f"<h1>{esc(mlabel(ym))}: বড় ঘটনা</h1>\n<p class=\"sub\">প্রতিদিনের সবচেয়ে গুরুত্বপূর্ণ খবর, নতুন থেকে পুরোনো</p>\n"]
    cur = None
    for it in items:
        if it["date"] != cur:
            cur = it["date"]
            h.append(f'<p class="dt"><a href="{day_path(cur)}">{esc(dlabel(cur, True))}</a></p>\n')
        h.append(f'<article><h3><a href="{day_path(it["date"])}#{esc(it["id"])}" style="text-decoration:none">{esc(it["title"])}</a></h3>'
                 f'<p>{esc(it["short"])}</p></article>\n')
    if not items:
        h.append("<p>এই মাসে এখনো বড় ঘটনা জমেনি।</p>\n")
    older = [m for m in months if m < ym][:1]
    newer = [m for m in reversed(months) if m > ym][:1]
    h.append('<div class="pn">' + (f'<a href="{month_path(older[0])}">← {esc(mlabel(older[0]))}</a>' if older else "<span></span>")
             + (f'<a class="r" href="{month_path(newer[0])}">{esc(mlabel(newer[0]))} →</a>' if newer else "") + "</div>\n")
    h.append(foot())
    return "".join(h)


def write(path: Path, text: str) -> bool:
    """বদলালে তবেই লেখে (কমিটে অকারণ বদল নয়)।"""
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True


def build_all(news_dir: Path | None = None, site_root: Path | None = None) -> list[str]:
    """সব পাতা বানায়; ফল: যে ফাইলগুলো বদলাল তাদের তালিকা (রিপো-মূল থেকে)।"""
    nd = news_dir or NEWS_DIR
    root = site_root or nd.parent
    index = read_json(nd / "index.json")
    idx = sorted(index.get("days", []), key=lambda d: d["date"], reverse=True)
    if not idx:
        return []
    dates = [d["date"] for d in idx]
    months_all = sorted({p.stem for p in (nd / "month").glob("*.json")}, reverse=True)
    changed = []

    def put(rel: str, text: str):
        if write(root / "news" / rel, text):
            changed.append(f"news/{rel}")

    days = {}
    for d in dates:
        f = nd / "day" / f"{d}.json"
        if f.exists():
            days[d] = read_json(f)
    months = {m: read_json(nd / "month" / f"{m}.json") for m in months_all}
    mset = set(months)
    for d, day in days.items():
        y, m, dd = d.split("-")
        put(f"{y}/{m}/{dd}/index.html", day_page(day, [x for x in dates if x in days], mset))
    for m, data in months.items():
        y, mm = m.split("-")
        put(f"{y}/{mm}/index.html", month_page(data, months_all))
    latest = days.get(index.get("latest") or dates[0]) or days[next(iter(days))]
    put("index.html", landing(latest, [d for d in idx if d["date"] in days], months_all))
    return changed


