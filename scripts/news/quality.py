def exam_point_problems(text: str, facts: list[dict]) -> list[str]:
    t = (text or "").strip()
    out = []
    if not t:
        return ["'পরীক্ষার জন্য গুরুত্বপূর্ণ' ফাঁকা"]
    m = _BANNED.search(t)
    if m:
        out.append(f"'পরীক্ষার জন্য গুরুত্বপূর্ণ'-এ নিষেধ করা কথা: “{m.group(0)}”")
    if len(t.split()) > EXAM_MAX_WORDS:
        out.append("'পরীক্ষার জন্য গুরুত্বপূর্ণ' দুই লাইনের বেশি")
    has_num = bool(ANY_DIGIT.search(t))
    has_name = any(_core(f.get("value", "")) and _core(f.get("value", "")) in t for f in facts or [])
    if not (has_num or has_name):
        out.append("'পরীক্ষার জন্য গুরুত্বপূর্ণ'-এ কোনো নাম বা সংখ্যা নেই")
    return out


def _core(v: str) -> str:
    """ছকের মানের মূল অংশ (বন্ধনী আর তার পরের ব্যাখ্যা বাদ), নাম মেলাতে।"""
    v = re.split(r"[(—,;]", str(v or ""))[0].strip()
    return v if len(v) >= 3 else ""


