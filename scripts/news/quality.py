def _domain(url: str) -> str:
    host = (urllib.parse.urlparse(url).hostname or "").lower().removeprefix("www.")
    parts = host.split(".")
    if len(parts) >= 3 and parts[-2] in {"com", "co", "org", "gov", "net", "ac", "edu"} and len(parts[-1]) == 2:
        return ".".join(parts[-3:])
    return ".".join(parts[-2:])


def item_problems(it: dict) -> list[str]:
    """প্রকাশযোগ্য এক খবরের সব শর্ত। ফাঁকা তালিকা = ঠিক আছে।"""
    p = []
    for k in ("title", "short", "detail"):
        if not str(it.get(k, "")).strip():
            p.append(f"{k} ফাঁকা")
    facts = it.get("facts") or []
    p += exam_point_problems(it.get("exam_point", ""), facts)
    good = [f for f in facts if str(f.get("label", "")).strip() and str(f.get("value", "")).strip()]
    if not (FACTS_MIN <= len(good) <= FACTS_MAX):
        p.append(f"'যা পরীক্ষায় লাগে' ছকে {bn_digits(len(good))} সারি (চাই {bn_digits(FACTS_MIN)}-{bn_digits(FACTS_MAX)})")
    srcs = [s for s in it.get("sources") or [] if str(s.get("url", "")).startswith("http") and s.get("name")]
    doms = {_domain(s["url"]) for s in srcs}
    if len(doms) < 2 and not any(trusted(d) for d in doms):
        p.append("দুটো আলাদা তথ্যসূত্র নেই (একটা হলে বিশ্বস্ত পত্রিকার হতে হবে)")
    word = excluded(it.get("title", ""), it.get("short", ""))
    if word:
        p.append(f"বাদের বিষয় (অপরাধ/গুজব/তারকা/কেলেঙ্কারি): “{word}”")
    alltext = " ".join([*(str(it.get(k, "")) for k in TEXT_FIELDS), *(str(f.get("value", "")) for f in facts),
                        *(str(f.get("label", "")) for f in facts)])
    left = spelling_left(alltext)
    if left:
        p.append("বানান-ধাপ পার হয়নি: " + ", ".join(left[:5]))
    if any(ascii_digits_left(str(it.get(k, ""))) for k in TEXT_FIELDS):
        p.append("ইংরেজি অঙ্ক রয়ে গেছে (সংখ্যা বাংলায় চাই)")
    return p


def check_day(day) -> list[str]:
    """পুরো দিনের ফাইল (dict) প্রকাশের আগে। ফেরত: ভুলের তালিকা (ফাঁকা = প্রকাশ চলবে)।"""
    errs = []
    if not isinstance(day, dict):
        return ["দিনের ফাইল JSON বস্তু নয়"]
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(day.get("date", ""))):
        errs.append("তারিখ নেই বা ভুল")
    items = [*(day.get("top") or []), *(day.get("more") or [])]
    if not items:
        errs.append("একটাও সংবাদ নেই")
    ids = set()
    for it in items:
        if not isinstance(it, dict):
            errs.append("একটা সংবাদ JSON বস্তু নয়")
            continue
        if it.get("id") in ids:
            errs.append(f"একই id দুবার: {it.get('id')}")
        ids.add(it.get("id"))
        for e in item_problems(it):
            errs.append(f"{it.get('id', '?')}: {e}")
    return errs
